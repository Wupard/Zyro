$files = @(
    "c:\Users\Yusuf Kahraman\Desktop\Zyro\index.html",
    "c:\Users\Yusuf Kahraman\Desktop\Zyro\app.js"
)

foreach ($file in $files) {
    Write-Host "Processing: $file"
    $data = [System.IO.File]::ReadAllBytes($file)
    
    # Strip BOM if present
    if ($data.Length -ge 3 -and $data[0] -eq 0xEF -and $data[1] -eq 0xBB -and $data[2] -eq 0xBF) {
        $data = $data[3..($data.Length-1)]
        Write-Host "  Stripped BOM"
    }
    
    $originalLen = $data.Length
    foreach ($rep in $replacements) {
        $data = Replace-ByteSequence -data $data -pattern $rep.moji -replacement $rep.correct
    }
    
    Write-Host ("  Length: {0} -> {1} (saved {2} bytes)" -f $originalLen, $data.Length, ($originalLen - $data.Length))
    [System.IO.File]::WriteAllBytes($file, $data)
    Write-Host "  Saved: $file"
}

Write-Host "All done!"
