# Fix mojibake encoding by binary byte replacement
# Turkish characters that were encoded as UTF-8, then each byte read as CP1252, then re-saved as UTF-8

function Replace-ByteSequence {
    param([byte[]]$data, [byte[]]$pattern, [byte[]]$replacement)
    $result = New-Object System.Collections.Generic.List[byte]
    $i = 0
    $pLen = $pattern.Length
    $dLen = $data.Length
    while ($i -lt $dLen) {
        if ($i -le ($dLen - $pLen)) {
            $match = $true
            for ($j = 0; $j -lt $pLen; $j++) {
                if ($data[$i + $j] -ne $pattern[$j]) { $match = $false; break }
            }
            if ($match) {
                $result.AddRange([byte[]]$replacement)
                $i += $pLen
                continue
            }
        }
        $result.Add($data[$i])
        $i++
    }
    return , $result.ToArray()
}

